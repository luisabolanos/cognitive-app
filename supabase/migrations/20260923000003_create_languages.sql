-- Idiomas soportados por la aplicacion
-- ============================================================

create table public.languages (
    id bigint generated by default as identity primary key,

    code varchar(10) not null unique,
    name varchar(100) not null,
    is_active boolean not null default true,

    created_at timestamptz not null default now()
);

comment on table public.languages is
'Idiomas disponibles para el contenido dinamico de la aplicacion.';

comment on column public.languages.code is
'Codigo ISO del idioma, por ejemplo es, en, pt.';

comment on column public.languages.name is
'Nombre del idioma.';
