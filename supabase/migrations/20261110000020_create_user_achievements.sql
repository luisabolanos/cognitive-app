-- Logros desbloqueados por cada usuario
-- ============================================================

create table public.user_achievements (
    id bigint generated by default as identity primary key,

    user_id uuid not null
        references public.profiles(id)
        on delete cascade,

    achievement_id bigint not null
        references public.achievements(id)
        on delete cascade,

    unlocked_at timestamptz not null default now(),

    constraint user_achievements_unique
        unique (user_id, achievement_id)
);

comment on table public.user_achievements is
'Registro de logros que han sido alcanzados por los usuarios.';
