-- Tabla de clasificacion (Rankings por ejercicio y global)
-- ============================================================

create table public.leaderboards (
    id bigint generated by default as identity primary key,

    user_id uuid not null
        references public.profiles(id)
        on delete cascade,

    exercise_id bigint
        references public.exercises(id)
        on delete cascade,

    period varchar(20) not null default 'all_time'
        constraint leaderboards_period_check
        check (period in ('daily', 'weekly', 'monthly', 'all_time')),

    score bigint not null default 0,

    updated_at timestamptz not null default now(),

    constraint leaderboards_unique_entry
        unique nulls not distinct (user_id, exercise_id, period)
);

comment on table public.leaderboards is
'Clasificacion de puntajes de usuarios. Si exercise_id es NULL, representa el ranking global.';
