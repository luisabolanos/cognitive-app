-- Catalogo de logros y sus traducciones
-- ============================================================

create table public.achievements (
    id bigint generated by default as identity primary key,

    code varchar(100) not null unique,
    icon_name varchar(100),

    condition_type varchar(50) not null,
    condition_value integer not null default 1,

    is_active boolean not null default true,
    created_at timestamptz not null default now()
);

comment on table public.achievements is
'Catalogo de logros desbloqueables en la aplicacion.';

comment on column public.achievements.condition_type is
'Tipo de condicion para desbloquear (ej. streak_days, sessions_count, high_score).';


create table public.achievement_translations (
    id bigint generated by default as identity primary key,

    achievement_id bigint not null
        references public.achievements(id)
        on delete cascade,

    language_id bigint not null
        references public.languages(id)
        on delete cascade,

    name varchar(150) not null,
    description text,

    created_at timestamptz not null default now(),

    constraint achievement_translations_unique
        unique (achievement_id, language_id)
);

comment on table public.achievement_translations is
'Traducciones de nombres y descripciones de los logros.';
