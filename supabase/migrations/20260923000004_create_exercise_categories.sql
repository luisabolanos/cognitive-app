-- Categorias cognitivas
-- ============================================================

create table public.exercise_categories (
    id bigint generated by default as identity primary key,

    code varchar(100) not null unique,

    created_at timestamptz not null default now()
);

comment on table public.exercise_categories is
'Categorias cognitivas asociadas a los ejercicios.';

comment on column public.exercise_categories.code is
'Identificador tecnico unico de la categoria.';
