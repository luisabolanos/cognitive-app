-- Progreso del usuario por ejercicio
-- ============================================================

create table public.user_progress (
    id bigint generated by default as identity primary key,

    user_id uuid not null
        references public.profiles(id)
        on delete cascade,

    exercise_id bigint not null
        references public.exercises(id)
        on delete cascade,

    current_difficulty_level integer not null default 1,
    max_difficulty_unlocked integer not null default 1,

    best_score integer not null default 0,
    best_accuracy numeric(5,2) not null default 0.00,

    total_sessions_completed integer not null default 0,
    total_time_played_ms bigint not null default 0,

    last_played_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),

    constraint user_progress_unique_user_exercise
        unique (user_id, exercise_id)
);

comment on table public.user_progress is
'Estado de avance, nivel adaptativo actual y records de un usuario en cada ejercicio.';
