-- Configuraciones de dificultad
-- ============================================================

create table public.exercise_configurations (
    id bigint generated by default as identity primary key,

    exercise_id bigint not null
        references public.exercises(id)
        on delete cascade,

    difficulty_level integer not null,

    configuration jsonb not null default '{}'::jsonb,

    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),

    constraint exercise_configurations_difficulty_check
        check (difficulty_level > 0),

    constraint exercise_configurations_unique_level
        unique (exercise_id, difficulty_level)
);

comment on table public.exercise_configurations is
'Configuraciones de dificultad para generar variantes de cada ejercicio.';

comment on column public.exercise_configurations.difficulty_level is
'Nivel de dificultad de la configuracion.';

comment on column public.exercise_configurations.configuration is
'Parametros especificos del ejercicio almacenados como JSONB.';
