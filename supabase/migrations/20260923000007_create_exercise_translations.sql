-- Traducciones de ejercicios
-- ============================================================

create table public.exercise_translations (
    id bigint generated by default as identity primary key,

    exercise_id bigint not null
        references public.exercises(id)
        on delete cascade,

    language_id bigint not null
        references public.languages(id)
        on delete cascade,

    name varchar(150) not null,
    description text,

    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),

    constraint exercise_translations_unique
        unique (exercise_id, language_id)
);

comment on table public.exercise_translations is
'Traducciones de los ejercicios segun el idioma.';

comment on column public.exercise_translations.name is
'Nombre traducido del ejercicio.';

comment on column public.exercise_translations.description is
'Descripcion traducida del ejercicio.';
