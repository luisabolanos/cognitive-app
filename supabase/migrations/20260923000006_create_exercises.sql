-- Catalogo de ejercicios
-- ============================================================

create table public.exercises (
    id bigint generated by default as identity primary key,

    category_id bigint not null
        references public.exercise_categories(id)
        on delete restrict,

    code varchar(100) not null unique,

    is_active boolean not null default true,

    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

comment on table public.exercises is
'Catalogo de ejercicios cognitivos disponibles en la aplicacion.';

comment on column public.exercises.code is
'Identificador tecnico unico del ejercicio.';

comment on column public.exercises.is_active is
'Indica si el ejercicio esta disponible para los usuarios.';
