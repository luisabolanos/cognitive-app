-- Traducciones de categorias cognitivas
-- ============================================================

create table public.exercise_category_translations (
    id bigint generated by default as identity primary key,

    category_id bigint not null
        references public.exercise_categories(id)
        on delete cascade,

    language_id bigint not null
        references public.languages(id)
        on delete cascade,

    name varchar(150) not null,
    description text,

    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),

    constraint exercise_category_translations_unique
        unique (category_id, language_id)
);

comment on table public.exercise_category_translations is
'Traducciones de las categorias cognitivas segun el idioma.';

comment on column public.exercise_category_translations.name is
'Nombre traducido de la categoria.';

comment on column public.exercise_category_translations.description is
'Descripcion traducida de la categoria.';
